// ---------- rough text-fit check ----------
const warn = [];
for (const f of fit) {
  const o = f.o;
  const fs = o.fontSize;
  const cw = (o.fontFace === "Courier New" ? 0.6 : 0.53) * (o.bold ? 1.06 : 1) * fs / 72;
  const w = o.w - (f.bullets ? 0.35 : 0);
  const lineH = fs * 1.2 / 72;
  let lines = 0;
  const paras = f.text.split("\n");
  for (const p of paras) {
    const words = p.split(" ");
    let cur = 0, l = 1;
    for (const wd of words) {
      const len = (wd.length + 1) * cw;
      if (len > w + 0.01) warn.push(`slide ${f.n}: word too wide "${wd}" (${len.toFixed(2)} > ${w.toFixed(2)})`);
      if (cur + len > w + 0.01 && cur > 0) { l += 1; cur = len; } else cur += len;
    }
    lines += l;
  }
  const h = lines * lineH + (paras.length - 1) * ((o.paraSpaceAfter || 0) / 72);
  if (h > o.h + 0.02) warn.push(`slide ${f.n}: "${f.text.slice(0, 40)}" needs ${h.toFixed(2)} in, box ${o.h}`);
}

